export function getAllowedWeakTopicSlugs(chapterSlug: string, chapterTopicSlugs: string[]) {
  // Normalize alias slugs (e.g. 'the-rise-of-nationalism-in-europe' -> 'rise-of-nationalism-in-europe')
  const strippedSlug = chapterSlug.replace(/^the-/, '');
  const withTheSlug = chapterSlug.startsWith('the-') ? chapterSlug : `the-${chapterSlug}`;

  const chapterSpecific = [
    ...(CHAPTER_WEAK_TOPIC_SLUGS[chapterSlug] ?? []),
    ...(CHAPTER_WEAK_TOPIC_SLUGS[strippedSlug] ?? []),
    ...(CHAPTER_WEAK_TOPIC_SLUGS[withTheSlug] ?? []),
  ];

  return new Set([
    ...chapterTopicSlugs,
    ...STANDARD_LESSON_SLUGS,
    ...chapterSpecific,
  ]);
}

export function findInvalidWeakTopicSlug(params: {
  chapterSlug: string;
  chapterTopicSlugs: string[];
  weakTopicSlugs: string[];
}) {
  const allowedWeakTopicSlugs = getAllowedWeakTopicSlugs(params.chapterSlug, params.chapterTopicSlugs);

  return params.weakTopicSlugs.find((weakTopicSlug) => !allowedWeakTopicSlugs.has(weakTopicSlug)) ?? null;
}
